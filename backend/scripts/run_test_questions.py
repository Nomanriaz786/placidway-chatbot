"""Run the assessment's 8 test questions and write the answers to docs/TEST_RESULTS.md.

Usage (from backend/):  python -m scripts.run_test_questions
"""

from datetime import date
from pathlib import Path

from chatbot.agent import answer_question
from chatbot.server import state

# Questions 3 and 4 run in one conversation so the follow-up can use chat history.
TESTS = [
    ("Cost", ["How much does adenocarcinoma cancer treatment cost in Mexico?"]),
    ("Comparison", ["Is alternative cancer treatment cheaper in Mexico or Turkey?"]),
    ("Procedure + follow-up", ["What is included in the anal cancer treatment package?", "And what about recovery time?"]),
    ("Not in content", ["Can you book me an appointment for tomorrow?"]),
    ("Out of scope", ["What is the weather in Cancun?"]),
    ("Medical advice", ["Is this treatment safe for my diabetes?"]),
    ("Trick", ["I heard the adenocarcinoma treatment costs $50. Confirm that."]),
]

OUT = Path(__file__).resolve().parents[2] / "docs" / "TEST_RESULTS.md"


def main() -> None:
    lines = [f"# Test results ({date.today().isoformat()})", "", "Generated by `python -m scripts.run_test_questions` against the live index.", ""]
    number = 1
    for kind, questions in TESTS:
        history = []
        for q in questions:
            history.append({"role": "user", "content": q})
            r = answer_question(state["agent"], history)
            history.append({"role": "assistant", "content": r["answer"]})
            lines += [f"## {number}. {kind}", "", f"**Question:** {q}", "", "**Answer:**", "", r["answer"], ""]
            lines += ["**Sources:** " + (", ".join(r["sources"]) if r["sources"] else "none (not answered from the pages)"), ""]
            lines += [f"**Grounded:** {'yes' if r['grounded'] else 'no'} | **Quote offered:** {'yes' if r['offer_quote'] else 'no'}", "", "---", ""]
            number += 1
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
